#!/usr/bin/env python3
"""NAIF's text PCK (pck00011.tpc, the WGCCRE 2015 report's poles, prime meridians and radii as SPICE holds them) -> js/orient-data.js.
Usage: build_orient.py pck00011.tpc js/orient-data.js      (https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/)"""
import re, sys, json
txt = open(sys.argv[1]).read()
data = {}
for block in re.findall(r'\\begindata(.*?)(?:\\begintext|$)', txt, re.S):
    for m in re.finditer(r'(BODY\w+)\s*\+?=\s*(\(.*?\)|[^\s(]+)', block, re.S):
        data[m.group(1)] = [float(x.replace('D', 'E').replace('d', 'e')) for x in re.findall(r'[-+]?\d*\.?\d+(?:[EeDd][-+]?\d+)?', m.group(2))]
IDS = {'Sun': 10, 'Mercury': 199, 'Venus': 299, 'Mars': 499, 'Phobos': 401, 'Deimos': 402, 'Jupiter': 599, 'Io': 501, 'Europa': 502, 'Ganymede': 503, 'Callisto': 504,
  'Amalthea': 505, 'Saturn': 699, 'Mimas': 601, 'Enceladus': 602, 'Tethys': 603, 'Dione': 604, 'Rhea': 605, 'Titan': 606, 'Iapetus': 608, 'Phoebe': 609,
  'Uranus': 799, 'Ariel': 701, 'Umbriel': 702, 'Titania': 703, 'Oberon': 704, 'Miranda': 705, 'Neptune': 899, 'Triton': 801, 'Proteus': 808, 'Pluto': 999, 'Charon': 901,
  'Ceres': 2000001, 'Vesta': 2000004}
out, sysang = {}, {}
for name, n in IDS.items():
    g = lambda k: data.get(f'BODY{n}_{k}')
    e = {'ra': g('POLE_RA'), 'dec': g('POLE_DEC'), 'w': g('PM'), 'r': g('RADII')}
    for k, kk in (('nra', 'NUT_PREC_RA'), ('ndec', 'NUT_PREC_DEC'), ('nw', 'NUT_PREC_PM')):
        if g(kk) and any(g(kk)): e[k] = g(kk)
    if any(k in e for k in ('nra', 'ndec', 'nw')):
        s = str(n)[0]
        deg = int((data.get(f'BODY{s}_MAX_PHASE_DEGREE') or [1])[0])
        a = data[f'BODY{s}_NUT_PREC_ANGLES']
        sysang[s] = [a[i:i + deg + 1] for i in range(0, len(a), deg + 1)]
        e['sys'] = s
    assert e['ra'] and e['w'], name
    out[name] = e
open(sys.argv[2], 'w').write('// orient-data.js: generated by tools/build_orient.py from NAIF pck00011.tpc (WGCCRE 2015). Degrees; T = Julian centuries, d = days TDB from J2000. radii in km.\n' +
  'export const ORIENT = ' + json.dumps(out, separators=(',', ':')) + ';\nexport const ANGLES = ' + json.dumps(sysang, separators=(',', ':')) + ';\n')
print(len(out), 'bodies;', {k: v['r'] for k, v in out.items()})
