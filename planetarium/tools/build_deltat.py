#!/usr/bin/env python3
"""js/deltat-data.js from Morrison, Stephenson, Hohenkerk, Zawilski (2021) Table S15 (v. 2020) and the IERS EOP 20 C04 series.
Usage: build_deltat.py Table-S15.2020.txt eopc04.1962-now dat.c ../js/deltat-data.js"""
import re, sys
s15, eop, dat, out = sys.argv[1:5]
rows = [[float(x) for x in l.split()[1:]] for l in open(s15) if re.match(r'^ *\d+ +-?\d', l)]
leap = [[int(y), int(m), float(d)] for y, m, d in re.findall(r'\{ *(\d{4}), *(\d+), *([\d.]+) *\}', open(dat).read())]
drift = re.search(r'drift\[\]\[2\] = \{(.*?)\};', open(dat).read(), re.S).group(1); drift = [[float(a), float(b)] for a, b in re.findall(r'\{ *([\d.]+), *([\d.]+) *\}', drift)]
def tai_utc(mjd):
    import datetime
    d = datetime.date(1858, 11, 17) + datetime.timedelta(days=mjd); v = None
    for i, (y, m, x) in enumerate(leap):
        if (d.year, d.month) >= (y, m): v = x + ((mjd - drift[i][0]) * drift[i][1] if i < len(drift) else 0)
    return v
pts = []
for l in open(eop):
    f = l.split()
    if l.startswith('#') or len(f) < 8: continue
    mjd = float(f[4]); ut1_utc = float(f[7])
    pts.append((mjd, 32.184 + tai_utc(int(mjd)) - ut1_utc))
t0 = pts[0][0]; step = 30; D = dict(pts); last = pts[-1][0]
tab = [round(D[t0 + k * step], 3) for k in range(int((last - t0) // step) + 1)]
js = 'const ds = ' 
open(out, 'w').write('// deltat-data.js: generated by tools/build_deltat.py.\n// S15: TT - UT1 (s), cubic pieces [from, to, a0..a3], Morrison, Stephenson, Hohenkerk and Zawilski 2021, Proc. R. Soc. A 477, 20200776, Table S15 v. 2020.\n' +
  'export const S15 = ' + repr(rows).replace(' ', '') + ';\n// TT - UT1 (s) every 30 days from MJD EOP0: IERS EOP 20 C04.\nexport const EOP0 = %d, EOP_STEP = %d;\nexport const EOP = ' % (t0, step) + repr(tab).replace(' ', '') +
  ';\n// TAI - UTC: [MJD from, seconds] since 1972 (IERS), and [MJD from, seconds, MJD of drift origin, s/day] for 1962-1971.\nexport const LEAP = ' + repr([[(__import__('datetime').date(y, m, 1) - __import__('datetime').date(1858, 11, 17)).days, d] + (drift[i] if i < len(drift) else []) for i, (y, m, d) in enumerate(leap)]).replace(' ', '') + ';\n')
print(len(rows), len(tab), tab[0], tab[-1], last)
